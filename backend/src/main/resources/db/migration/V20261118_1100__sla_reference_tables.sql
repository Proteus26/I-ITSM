-- Minimal versions of it_services and sla_events so the P4 module (reports, search) can read them.
-- The SLA module (P3) extends these tables with ALTER TABLE rather than recreating them.

create table it_services (
    id   bigint generated by default as identity primary key,
    name varchar(100) not null unique
);

alter table incidents
    add constraint fk_incidents_service foreign key (service_id) references it_services (id);

create table sla_events (
    id          bigint generated always as identity primary key,
    incident_id bigint      not null references incidents (id) on delete cascade,
    type        varchar(30) not null check (type in ('WARNING', 'RESPONSE_BREACH', 'RESOLUTION_BREACH')),
    occurred_at timestamptz not null default now()
);

create index idx_sla_events_incident_type on sla_events (incident_id, type);
